def tr(language: str, key: str, **values: object) -> str:
    catalog = _TEXT.get(language, _TEXT[DEFAULT_LANGUAGE])
    text = catalog.get(key, _TEXT[DEFAULT_LANGUAGE].get(key, key))
    return text.format(**values)


def has_han(text: str) -> bool:
    return _HAN_RE.search(text) is not None


def localize_legacy(text: object, language: str) -> str:
    """Translate established engineering text while preserving raw tokens."""
    source = str(text)
    if language != "en" or not has_han(source):
        return source
    exact = _EXACT_EN.get(source)
    if exact is not None:
        return exact
    translated = source
    for chinese, english in sorted(_REPLACE_EN, key=lambda item: len(item[0]), reverse=True):
        translated = translated.replace(chinese, english)
    translated = (
        translated.replace("：", ": ")
        .replace("；", "; ")
        .replace("，", ", ")
        .replace("。", ".")
        .replace("（", " (")
        .replace("）", ")")
        .replace("“", '"')
        .replace("”", '"')
        .replace("？", "?")
        .replace("、", ", ")
        .replace("→", " -> ")
    )
    return translated


class LocalizedStringVar(tk.StringVar):
    """StringVar that keeps a source string and rerenders on language change."""

    def __init__(
        self,
        master: tk.Misc,
        language_getter: Callable[[], str],
        value: object = "",
    ) -> None:
        self._language_getter = language_getter
        self._source_value = str(value)
        super().__init__(master=master, value=localize_legacy(value, language_getter()))

    def set(self, value: object) -> None:
        self._source_value = str(value)
        super().set(localize_legacy(value, self._language_getter()))

    def refresh_language(self) -> None:
        super().set(localize_legacy(self._source_value, self._language_getter()))


class LocalizedMessageBox:
    """Proxy translating existing messagebox titles/messages at call time."""

    def __init__(self, backend: object) -> None:
        self._backend = backend
        self._language_getter: Callable[[], str] = lambda: DEFAULT_LANGUAGE

    def set_language_getter(self, getter: Callable[[], str]) -> None:
        self._language_getter = getter

    def __getattr__(self, name: str):
        target = getattr(self._backend, name)

        def translated_call(*args, **kwargs):
            language = self._language_getter()
            localized_args = list(args)
            if len(localized_args) >= 1:
                localized_args[0] = localize_legacy(localized_args[0], language)
            if len(localized_args) >= 2:
                localized_args[1] = localize_legacy(localized_args[1], language)
            if "title" in kwargs:
                kwargs["title"] = localize_legacy(kwargs["title"], language)
            if "message" in kwargs:
                kwargs["message"] = localize_legacy(kwargs["message"], language)
            return target(*localized_args, **kwargs)

        return translated_call
